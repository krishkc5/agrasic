# Waveform dumping for the regression stages -- opt in, off by default.
#
#   WAVES=1 bash tb/rv32i_regression/smoke.sh
#
# Writes <repo>/waves/<stage>.fst. Surfer and GTKWave both open FST directly,
# and it is a fraction of the size of VCD. Nothing is traced unless WAVES=1,
# so the normal regression and verify_all.sh are completely unaffected --
# tracing costs real simulation time on the longer stages.
#
# Knobs, all optional:
#   WAVE_FORMAT=fst|vcd   default fst. Use vcd only if you need to read it
#                         as text; it is several times larger.
#   WAVE_START=<ns>       start dumping at this sim time instead of 0. The
#                         way to skip boot and land on the interesting part.
#   WAVE_DEPTH=<n>        hierarchy levels below the testbench top to trace.
#                         Unset means everything.
#   WAVE_DIR=<path>       where files land. Default <repo>/waves.
#
# Two Verilator limitations are worth knowing, because the obvious
# SystemVerilog ways to control trace size DO NOT work. Both measured on
# Verilator 5.020, not assumed:
#
#   - $dumpvars' scope and level arguments are IGNORED. $dumpvars(0, top.dut)
#     dumps the entire design, byte-for-byte identical to $dumpvars(0, top).
#     Use WAVE_DEPTH (Verilator's --trace-depth) to narrow it instead.
#   - $dumpoff and $dumpon are IGNORED. A dump window can be opened but not
#     closed, so WAVE_START works by delaying the $dumpvars call itself and
#     there is deliberately no WAVE_STOP.
#
# How it works: rather than editing seventeen testbenches, this generates a
# one-off wave_dump module and `bind`s it into whichever testbench top the
# calling stage names. The generated file lives in the stage's scratch build
# directory and is never checked in.

# wave_setup <top_module> <output_basename>
# Sets WAVE_ARGS (extra verilator arguments, empty when WAVES is off) and
# WAVE_OUT (the file that will be written). Call it after cd'ing into the
# stage's build directory, then pass $WAVE_ARGS -- unquoted -- to verilator.
wave_setup() {
  WAVE_ARGS=""
  WAVE_OUT=""
  [ "${WAVES:-0}" = "1" ] || return 0

  local top="$1" name="$2"
  local fmt="${WAVE_FORMAT:-fst}"
  local dir="${WAVE_DIR:-$BASE/waves}"

  mkdir -p "$dir" || { echo "[waves] cannot create $dir"; return 1; }
  WAVE_OUT="$dir/${name}.${fmt}"
  # Clear any previous run's file so a build that dies cannot leave a stale
  # waveform behind looking like a fresh one.
  rm -f "$WAVE_OUT"

  local delay=""
  [ -n "${WAVE_START:-}" ] && delay="#${WAVE_START}ns;"

  cat > wave_dump.sv <<SV
// Generated by waves.sh for this run only. Not part of the design, and not
// compiled in unless WAVES=1.
module wave_dump;
  initial begin
    ${delay}
    \$dumpfile("${WAVE_OUT}");
    \$dumpvars(0, ${top});
  end
endmodule
bind ${top} wave_dump u_wave_dump();
SV

  if [ "$fmt" = "vcd" ]; then
    WAVE_ARGS="--trace --trace-structs wave_dump.sv"
  else
    WAVE_ARGS="--trace-fst --trace-structs wave_dump.sv"
  fi
  [ -n "${WAVE_DEPTH:-}" ] && WAVE_ARGS="--trace-depth ${WAVE_DEPTH} $WAVE_ARGS"
  return 0
}

# wave_report -- say where the waveform landed, or complain if none appeared.
wave_report() {
  [ "${WAVES:-0}" = "1" ] || return 0
  if [ -s "${WAVE_OUT:-/nonexistent}" ]; then
    echo "[waves] $(du -h "$WAVE_OUT" | cut -f1) -> $WAVE_OUT"
  else
    echo "[waves] WARNING: no waveform written (expected $WAVE_OUT)"
  fi
}
